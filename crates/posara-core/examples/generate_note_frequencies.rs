// cargo run -p posara-core --features rp32 --example generate_note_frequencies > crates/posara-core/src/sfx/seq/note_frequencies.rs
#[cfg(not(feature = "rp32"))]
compile_error!("generate the table with --features rp32 to preserve device math bits");

fn main() {
    println!("// Generated by examples/generate_note_frequencies.rs with rp32.");
    println!("pub const TABLE: [f32; 256] = [");
    for note in 0..=u8::MAX {
        let value = 440.0 * posara_core::math::powf(2.0, (note as f32 - 69.0) / 12.0);
        println!("    f32::from_bits(0x{:08x}),", value.to_bits());
    }
    println!("];");
}
