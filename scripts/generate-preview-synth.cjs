#!/usr/bin/env node
// device-preview.html: m=sin(2θ), deviation=f*(.2+1.6*tone/10).
const fs = require('node:fs');
const path = require('node:path');
const output = path.join(__dirname, '../crates/posara-core/src/sfx/preview_tables.rs');

const rows = Array.from({ length: 11 }, (_, tone) =>
  Array.from({ length: 1025 }, (_, index) => {
    const theta = 2 * Math.PI * index / 1024;
    const beta = 0.05 + 0.1 * tone + 0.0195 * tone * tone;
    return Math.round(32767 * Math.sin(theta + beta * (1 - Math.cos(2 * theta))));
  })
);
const curve = Array.from({ length: 257 }, (_, index) => {
  const value = index === 0 ? 1 : index === 256 ? 0 :
    (Math.pow(350, -index / 256) - 1 / 350) / (1 - 1 / 350);
  const bytes = Buffer.alloc(4);
  bytes.writeFloatLE(value);
  return `f32::from_bits(0x${bytes.readUInt32LE().toString(16).padStart(8, '0')})`;
});
const generated = '// Generated by scripts/generate-preview-synth.cjs; do not edit.\n' +
  '// Integrated frequency FM, beta=.05+.1*tone+.0195*tone^2; finite exponential floor 1/350.\n' +
  '#[cfg(any(test,feature="rp32",all(target_os="none",target_pointer_width="32")))]\n' +
  'pub(super) const FM:[[i16;1025];11]=[\n' +
  rows.map(row => '    [' + row.join(',') + '],').join('\n') + '\n];\n' +
  '#[cfg_attr(all(target_arch="arm",target_os="none"),unsafe(link_section=".data.ram_func"))]\n' +
  'pub(super) static DECAY:[f32;257]=[\n' +
  curve.map(value => '    ' + value + ',').join('\n') + '\n];\n';

if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== generated) throw Error('preview tables are stale');
} else {
  fs.writeFileSync(output, generated);
}
